from __future__ import annotations

import numpy as np
import torch

from timesfm3.torch import configs, util
from timesfm3.torch import cpm_revin_refine as refine_lib
from timesfm3.torch import model as model_lib


def f32(values) -> str:
    flat = np.asarray(values, dtype=np.float32).ravel()
    return ", ".join(
        np.format_float_positional(v, unique=True, trim="0") for v in flat
    )


def bools(values) -> str:
    return ", ".join("true" if v else "false" for v in np.asarray(values).ravel())


def const(name: str, kind: str, values, fmt=f32) -> str:
    count = np.asarray(values).size
    return f"const {name}: [{kind}; {count}] = [{fmt(values)}];\n"


def detrend(values: np.ndarray, masks: np.ndarray):
    """`TimesFM3Torch.decode`'s detrending, verbatim, for one variate."""
    ctx_vals = torch.from_numpy(values)[None, None, :]
    ctx_masks = torch.from_numpy(masks)[None, None, :]
    context = values.shape[-1]
    t_ctx = torch.arange(-(context - 1), 1, dtype=torch.float32)
    t_ctx_bvc_normalized = t_ctx[None, None, :] / context
    valid = ~ctx_masks
    n_v = valid.float().sum(dim=-1, keepdim=True)
    sum_t = torch.where(valid, t_ctx_bvc_normalized, 0.0).sum(dim=-1, keepdim=True)
    sum_t2 = torch.where(valid, t_ctx_bvc_normalized**2, 0.0).sum(dim=-1, keepdim=True)
    sum_y = torch.where(valid, ctx_vals, 0.0).sum(dim=-1, keepdim=True)
    sum_ty = torch.where(valid, t_ctx_bvc_normalized * ctx_vals, 0.0).sum(
        dim=-1, keepdim=True
    )
    det = n_v * sum_t2 - sum_t**2
    safe_det = torch.where(det == 0.0, 1.0, det)
    m_trend = torch.where(det == 0.0, 0.0, (n_v * sum_ty - sum_t * sum_y) / safe_det)
    c_trend = torch.where(
        det == 0.0,
        torch.where(n_v > 0, sum_y / torch.clamp_min(n_v, 1.0), 0.0),
        (sum_y - m_trend * sum_t) / torch.clamp_min(n_v, 1.0),
    )
    detrended = ctx_vals - (m_trend * t_ctx_bvc_normalized + c_trend)
    mean_y = sum_y / torch.clamp_min(n_v, 1.0)
    sum_y2 = torch.where(valid, ctx_vals**2, 0.0).sum(dim=-1, keepdim=True)
    std_orig = torch.sqrt(
        torch.clamp_min(sum_y2 / torch.clamp_min(n_v, 1.0) - mean_y**2, 0.0)
    )
    sum_yd = torch.where(valid, detrended, 0.0).sum(dim=-1, keepdim=True)
    mean_yd = sum_yd / torch.clamp_min(n_v, 1.0)
    sum_yd2 = torch.where(valid, detrended**2, 0.0).sum(dim=-1, keepdim=True)
    std_det = torch.sqrt(
        torch.clamp_min(sum_yd2 / torch.clamp_min(n_v, 1.0) - mean_yd**2, 0.0)
    )
    apply = std_det < 0.5 * std_orig
    out = torch.where(apply, detrended, ctx_vals)
    return out[0, 0].numpy(), float(m_trend), float(c_trend), bool(apply)


def main() -> None:
    rng = np.random.default_rng(3)
    out = ["// Generated by parity/prep_cases.py from the PyTorch reference. Do not edit.\n"]

    # Running stats over three patches, the first partly masked.
    values = rng.normal(5.0, 3.0, 96).astype(np.float32)
    masks = np.zeros(96, dtype=bool)
    masks[:20] = True
    masks[50:54] = True
    n, mu, sigma = util.get_running_stats(
        torch.from_numpy(values).view(1, 1, 3, 32), torch.from_numpy(masks).view(1, 1, 3, 32)
    )
    stats = torch.stack([n, mu, sigma], dim=-1)[0, 0].numpy()
    out.append(const("STATS_VALUES", "f32", values))
    out.append(const("STATS_MASKS", "bool", masks, bools))
    out.append(const("STATS_EXPECTED", "f32", stats))

    # Detrending: a clear trend with leading padding, and plain noise.
    cases = []
    t = np.arange(64, dtype=np.float32)
    trend = (3.0 + 0.8 * t + rng.normal(0, 1.0, 64)).astype(np.float32)
    trend_masks = np.zeros(64, dtype=bool)
    trend_masks[:10] = True
    trend[:10] = 0.0
    noise = rng.normal(10.0, 4.0, 64).astype(np.float32)
    for name, (v, m) in {
        "TREND": (trend, trend_masks),
        "NOISE": (noise, np.zeros(64, dtype=bool)),
    }.items():
        expected, slope, intercept, apply = detrend(v, m)
        out.append(const(f"DETREND_{name}_VALUES", "f32", v))
        out.append(const(f"DETREND_{name}_MASKS", "bool", m, bools))
        out.append(const(f"DETREND_{name}_EXPECTED", "f32", expected))
        cases.append(
            f"(&DETREND_{name}_VALUES, &DETREND_{name}_MASKS, &DETREND_{name}_EXPECTED, "
            f"{f32([slope])}, {f32([intercept])}, {str(apply).lower()})"
        )
    out.append(
        "#[allow(clippy::type_complexity)]\n"
        "const DETREND_CASES: &[(&[f32], &[bool], &[f32], f32, f32, bool)] = &["
        + ", ".join(cases)
        + "];\n"
    )

    # Residual-block input rows of a covariate (not target) over four patches.
    small = model_lib.TimesFM3Torch(
        residual_block_config=configs.ResidualBlockConfig(
            hidden_dims=8, output_dims=8, use_bias=False, activation="relu"
        ),
        transformer_config=configs.StackedTransformersConfig(
            num_layers=1,
            transformer=configs.TransformerConfig(
                model_dims=8,
                hidden_dims=8,
                num_heads=2,
                attention_norm="rms",
                feedforward_norm="rms",
                qk_norm="rms",
                use_bias=False,
                use_rope_seq=True,
                use_rope_var=False,
                ff_activation="relu",
                deterministic=True,
            ),
        ),
    )
    row_values = rng.normal(2.0, 1.5, 128).astype(np.float32)
    row_masks = np.zeros(128, dtype=bool)
    row_masks[:40] = True
    row_masks[100:] = True
    row_values[row_masks] = 0.0
    with torch.no_grad():
        resblock_input, _, patch_mask, _, _ = small._preprocess(
            torch.from_numpy(row_values).view(1, 1, 4, 32),
            torch.from_numpy(row_masks).view(1, 1, 4, 32),
            torch.zeros(1, 1, 4, dtype=torch.bool),
        )
    out.append(const("ROWS_VALUES", "f32", row_values))
    out.append(const("ROWS_MASKS", "bool", row_masks, bools))
    out.append(const("ROWS_EXPECTED", "f32", resblock_input[0, 0].numpy()))
    out.append(const("ROWS_FULLY_MASKED", "bool", patch_mask[0, 0].numpy(), bools))

    # Iterative CPM RevIN refinement: four patches, the last two horizon.
    patches = 4
    raw = rng.normal(0.0, 1.0, (1, 1, patches, 576)).astype(np.float32)
    ref_stats = np.stack(
        [
            np.array([32, 64, 96, 96], dtype=np.float32),
            rng.normal(10.0, 2.0, patches).astype(np.float32),
            rng.uniform(1.0, 4.0, patches).astype(np.float32),
        ],
        axis=-1,
    )
    cpm = torch.zeros(1, patches, dtype=torch.bool)
    cpm[:, 2:] = True
    mu, sigma = refine_lib.cpm_iterative_revin_refine(
        torch.from_numpy(raw),
        revin_n=torch.from_numpy(ref_stats[None, None, :, 0].copy()),
        revin_mu=torch.from_numpy(ref_stats[None, None, :, 1].copy()),
        revin_sigma=torch.from_numpy(ref_stats[None, None, :, 2].copy()),
        patch_cpm_mask=cpm,
        median_q_idx=4,
        rolls=2,
        patch_len=32,
        num_quantiles=9,
        value_clip=1e20,
    )
    out.append(const("REFINE_RAW", "f32", raw))
    out.append(const("REFINE_STATS", "f32", ref_stats))
    out.append("const REFINE_FROM: usize = 2;\n")
    out.append(const("REFINE_EXPECTED", "f32", torch.stack([mu, sigma], -1)[0, 0].numpy()))

    # Stitching three 64-point patch forecasts.
    preds = rng.normal(0.0, 5.0, (1, 1, 3, 64, 9)).astype(np.float32)
    stitched = util.stitch_patches(torch.from_numpy(preds), 32)
    out.append(const("STITCH_INPUT", "f32", preds))
    out.append(const("STITCH_EXPECTED", "f32", stitched[0, 0].numpy()))

    print("".join(out), end="")


if __name__ == "__main__":
    main()
