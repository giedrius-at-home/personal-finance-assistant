"""Authenticated, bounded receipt boundary for Firefly III webhooks."""

from __future__ import annotations

import hashlib
import hmac
import json
import threading
from collections import OrderedDict
from collections.abc import Callable
from datetime import UTC, datetime
from decimal import Decimal
from enum import StrEnum
from typing import Any
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, SecretStr, ValidationError

MAX_WEBHOOK_BYTES = 1024 * 1024
MAX_SIGNATURE_HEADER_BYTES = 1024
DEFAULT_TIMESTAMP_TOLERANCE_SECONDS = 300
DEFAULT_REPLAY_CAPACITY = 10_000
MIN_WEBHOOK_SECRET_BYTES = 24


class WebhookAuthenticationError(RuntimeError):
    """A generic authentication failure without body or secret context."""


class WebhookPayloadError(RuntimeError):
    """A signed payload violated the pinned Firefly envelope contract."""


class ReplayCapacityError(RuntimeError):
    """Replay protection is full and receipt must fail closed."""


class FireflyWebhookTrigger(StrEnum):
    ANY = "ANY"
    STORE_TRANSACTION = "STORE_TRANSACTION"
    UPDATE_TRANSACTION = "UPDATE_TRANSACTION"
    DESTROY_TRANSACTION = "DESTROY_TRANSACTION"
    STORE_BUDGET = "STORE_BUDGET"
    UPDATE_BUDGET = "UPDATE_BUDGET"
    DESTROY_BUDGET = "DESTROY_BUDGET"
    STORE_UPDATE_BUDGET_LIMIT = "STORE_UPDATE_BUDGET_LIMIT"


class FireflyWebhookResponse(StrEnum):
    TRANSACTIONS = "TRANSACTIONS"
    ACCOUNTS = "ACCOUNTS"
    BUDGET = "BUDGET"
    RELEVANT = "RELEVANT"
    NONE = "NONE"


class FireflyWebhookEnvelope(BaseModel):
    """Pinned v0 message generated by Firefly III 6.6.6."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    uuid: UUID
    user_id: int = Field(ge=0)
    user_group_id: int = Field(ge=0)
    trigger: FireflyWebhookTrigger
    response: FireflyWebhookResponse
    url: str = Field(min_length=1, max_length=2048)
    version: str = Field(pattern="^v0$")
    content: dict[str, Any] | list[Any]


class FireflyWebhookVerifier:
    """Verify Firefly's v1 HMAC signature over timestamp and raw bytes."""

    def __init__(
        self,
        secret: SecretStr | str,
        *,
        timestamp_tolerance_seconds: int = DEFAULT_TIMESTAMP_TOLERANCE_SECONDS,
    ) -> None:
        configured = secret if isinstance(secret, SecretStr) else SecretStr(secret)
        raw_secret = configured.get_secret_value()
        if len(raw_secret.encode()) < MIN_WEBHOOK_SECRET_BYTES:
            raise ValueError("webhook secret must contain at least 24 bytes")
        if not 1 <= timestamp_tolerance_seconds <= 3600:
            raise ValueError("timestamp tolerance must be between 1 and 3600 seconds")
        self._secret = raw_secret.encode()
        self._tolerance = timestamp_tolerance_seconds

    def verify(self, raw_body: bytes, signature_header: str, *, now: int) -> int:
        """Return the signed timestamp or raise one generic safe error."""

        try:
            timestamp, candidates = self._parse_header(signature_header)
        except (TypeError, ValueError) as error:
            raise WebhookAuthenticationError("webhook authentication failed") from error
        if abs(now - timestamp) > self._tolerance:
            raise WebhookAuthenticationError("webhook authentication failed")
        signed_payload = str(timestamp).encode() + b"." + raw_body
        expected = hmac.new(
            self._secret, signed_payload, digestmod=hashlib.sha3_256
        ).hexdigest()
        if not any(
            hmac.compare_digest(expected, candidate) for candidate in candidates
        ):
            raise WebhookAuthenticationError("webhook authentication failed")
        return timestamp

    @staticmethod
    def _parse_header(value: str) -> tuple[int, tuple[str, ...]]:
        if not value or len(value.encode()) > MAX_SIGNATURE_HEADER_BYTES:
            raise ValueError("invalid signature header")
        timestamp_values: list[str] = []
        candidates: list[str] = []
        for part in value.split(","):
            key, separator, candidate = part.strip().partition("=")
            if not separator or not key or not candidate:
                raise ValueError("invalid signature component")
            if key == "t":
                timestamp_values.append(candidate)
            elif key == "v1":
                candidates.append(candidate)
        if len(timestamp_values) != 1 or not timestamp_values[0].isascii():
            raise ValueError("invalid signature timestamp")
        if not timestamp_values[0].isdigit() or not candidates:
            raise ValueError("invalid signature values")
        if any(
            len(candidate) != 64
            or any(character not in "0123456789abcdef" for character in candidate)
            for candidate in candidates
        ):
            raise ValueError("invalid v1 signature")
        return int(timestamp_values[0]), tuple(candidates)


class InMemoryReplayGuard:
    """Bounded process-local UUID deduplication pending durable persistence."""

    def __init__(
        self,
        *,
        retention_seconds: int = DEFAULT_TIMESTAMP_TOLERANCE_SECONDS * 2,
        capacity: int = DEFAULT_REPLAY_CAPACITY,
    ) -> None:
        if retention_seconds < 1:
            raise ValueError("retention_seconds must be positive")
        if capacity < 1:
            raise ValueError("capacity must be positive")
        self._retention = retention_seconds
        self._capacity = capacity
        self._deliveries: OrderedDict[UUID, int] = OrderedDict()
        self._lock = threading.Lock()

    def claim(self, delivery_id: UUID, *, now: int) -> bool:
        """Atomically claim an ID; return false for a retained duplicate."""

        with self._lock:
            expiry_threshold = now - self._retention
            while self._deliveries:
                oldest_id, accepted_at = next(iter(self._deliveries.items()))
                if accepted_at > expiry_threshold:
                    break
                del self._deliveries[oldest_id]
            if delivery_id in self._deliveries:
                return False
            if len(self._deliveries) >= self._capacity:
                raise ReplayCapacityError("webhook replay protection is at capacity")
            self._deliveries[delivery_id] = now
            return True


class FireflyWebhookReceiver:
    """Authenticate raw input, validate it, then claim its delivery UUID."""

    def __init__(
        self,
        *,
        secret: SecretStr | str,
        clock: Callable[[], int] | None = None,
        replay_guard: InMemoryReplayGuard | None = None,
    ) -> None:
        self._verifier = FireflyWebhookVerifier(secret)
        self._clock = clock or (lambda: int(datetime.now(UTC).timestamp()))
        self._replay_guard = replay_guard or InMemoryReplayGuard()

    def receive(self, raw_body: bytes, signature_header: str) -> bool:
        """Return true for a new valid event and false for a valid duplicate."""

        now = self._clock()
        self._verifier.verify(raw_body, signature_header, now=now)
        try:
            payload = json.loads(raw_body, parse_float=Decimal)
            envelope = FireflyWebhookEnvelope.model_validate(payload)
        except (UnicodeDecodeError, json.JSONDecodeError, ValidationError) as error:
            raise WebhookPayloadError("invalid webhook payload") from error
        return self._replay_guard.claim(envelope.uuid, now=now)
